import { spawn } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const CLIPS = ["hero-site-reel", "process-proof"] as const;
type VideoAssets = Record<string, { desktop: string; mobile: string }>;
type ClipPaths = { incoming: string; publicDir: string; assetsModule: string };
type Encoder = (args: string[]) => Promise<void>;

const encode: Encoder = (args) => new Promise((resolve, reject) => {
  const child = spawn("ffmpeg", args, { stdio: ["ignore", "ignore", "pipe"], windowsHide: true });
  let errors = "";
  child.stderr.on("data", (data: Buffer) => { errors = (errors + data.toString()).slice(-4000); });
  child.on("error", (error) => reject(new Error(`Unable to run ffmpeg. Install it on PATH. ${error.message}`)));
  child.on("close", (code) => code === 0 ? resolve() : reject(new Error(`ffmpeg exited ${code}: ${errors}`)));
});

function encodingArgs(input: string, output: string, mobile: boolean): string[] {
  return [
    "-hide_banner", "-loglevel", "error", "-nostdin", "-y", "-i", input,
    "-map", "0:v:0", "-vf", mobile ? "scale=-2:min(720\\,trunc(ih/2)*2),setsar=1" : "scale=trunc(iw/2)*2:trunc(ih/2)*2,setsar=1",
    "-c:v", "libx264", "-preset", "slow", "-crf", mobile ? "23" : "20",
    "-pix_fmt", "yuv420p", "-g", mobile ? "4" : "8", "-keyint_min", mobile ? "4" : "8",
    "-sc_threshold", "0", "-an", "-map_metadata", "-1", "-movflags", "+faststart", output,
  ];
}

function hasFile(file: string): boolean {
  return existsSync(file) && statSync(file).isFile() && statSync(file).size > 0;
}

/** Only the two authored clip names are accepted; no shell or user-controlled paths. */
export async function processClips(paths: ClipPaths, run: Encoder = encode): Promise<VideoAssets> {
  mkdirSync(paths.publicDir, { recursive: true });
  const staging = mkdtempSync(path.join(paths.publicDir, ".encoding-"));
  const assets: VideoAssets = {};
  const outputs: string[] = [];
  try {
    for (const key of CLIPS) {
      const input = path.resolve(paths.incoming, `${key}.mp4`);
      const desktop = `${key}.mp4`;
      const mobile = `${key}-m.mp4`;
      if (hasFile(input)) {
        for (const [file, isMobile] of [[desktop, false], [mobile, true]] as const) {
          const output = path.join(staging, file);
          await run(encodingArgs(input, output, isMobile));
          if (!hasFile(output)) throw new Error(`Encoder produced no file: ${file}`);
          outputs.push(file);
        }
        assets[key] = { desktop, mobile };
      } else if (hasFile(path.join(paths.publicDir, desktop)) && hasFile(path.join(paths.publicDir, mobile))) {
        assets[key] = { desktop, mobile };
      }
    }
    // Publish only after every encode succeeds; a failed encode keeps existing media intact.
    for (const file of outputs) renameSync(path.join(staging, file), path.join(paths.publicDir, file));
    mkdirSync(path.dirname(paths.assetsModule), { recursive: true });
    writeFileSync(paths.assetsModule, `// Generated by scripts/process-clips.ts — do not edit by hand.\nexport const VIDEO_ASSETS: Record<string, { desktop: string; mobile: string }> = ${JSON.stringify(assets, null, 2)};\n`);
    return assets;
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  if (process.argv[2] !== "truecut") {
    console.error("usage: npm run clips -- truecut");
    process.exit(1);
  }
  processClips({
    incoming: "assets/incoming/truecut/clips",
    publicDir: "public/templates/truecut/clips",
    assetsModule: "src/app/(truecut)/truecut/videos.generated.ts",
  }).then((assets) => {
    console.log(`clips: truecut → ${Object.keys(assets).length} available`);
    for (const key of CLIPS) if (!assets[key]) console.log(`Awaiting assets/incoming/truecut/clips/${key}.mp4`);
  }).catch((error: unknown) => { console.error(error); process.exitCode = 1; });
}
