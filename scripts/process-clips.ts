import { spawn } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { TEMPLATES, type TemplateSlug } from "./templates.config";

export const INPUT_VIDEO = /\.(mp4|mov|webm|m4v)$/i;

export type VideoAssets = Record<string, { desktop: string; mobile: string }>;
export type ClipPaths = { incoming: string; publicDir: string; assetsModule: string };
export type Encoder = (args: string[]) => Promise<void>;

export const encode: Encoder = (args) =>
  new Promise((resolve, reject) => {
    const child = spawn("ffmpeg", args, { stdio: ["ignore", "ignore", "pipe"], windowsHide: true });
    let errors = "";
    child.stderr.on("data", (data: Buffer) => {
      errors = (errors + data.toString()).slice(-4000);
    });
    child.on("error", (error) => reject(new Error(`Unable to run ffmpeg. Install it on PATH. ${error.message}`)));
    child.on("close", (code) => (code === 0 ? resolve() : reject(new Error(`ffmpeg exited ${code}: ${errors}`))));
  });

export function encodingArgs(input: string, output: string, mobile: boolean): string[] {
  return [
    "-hide_banner",
    "-loglevel",
    "error",
    "-nostdin",
    "-y",
    "-i",
    input,
    "-map",
    "0:v:0",
    "-vf",
    mobile ? "scale=-2:min(720\\,trunc(ih/2)*2),setsar=1" : "scale=trunc(iw/2)*2:trunc(ih/2)*2,setsar=1",
    "-c:v",
    "libx264",
    "-preset",
    "slow",
    "-crf",
    mobile ? "23" : "20",
    "-pix_fmt",
    "yuv420p",
    "-g",
    mobile ? "4" : "8",
    "-keyint_min",
    mobile ? "4" : "8",
    "-sc_threshold",
    "0",
    "-an",
    "-map_metadata",
    "-1",
    "-movflags",
    "+faststart",
    output,
  ];
}

export function hasFile(file: string): boolean {
  return existsSync(file) && statSync(file).isFile() && statSync(file).size > 0;
}

export function renderVideoAssetsModule(assets: VideoAssets): string {
  const body = Object.keys(assets).length ? JSON.stringify(assets, null, 2) : "{}";
  const clipsMap = Object.keys(assets).length
    ? JSON.stringify(Object.fromEntries(Object.keys(assets).map((k) => [k, true])), null, 2)
    : "{}";
  return `// Generated by scripts/process-clips.ts — do not edit by hand.\nexport const VIDEO_ASSETS: Record<string, { desktop: string; mobile: string }> = ${body};\nexport const CLIPS: Record<string, boolean> = ${clipsMap};\n`;
}

export function resolveClipPaths(slug: string): ClipPaths {
  const clipsIncoming = path.join("assets", "incoming", slug, "clips");
  const rootIncoming = path.join("assets", "incoming", slug);
  const hasClipsInSubdir = existsSync(clipsIncoming) && readdirSync(clipsIncoming).some((f) => INPUT_VIDEO.test(f));
  const incoming = hasClipsInSubdir ? clipsIncoming : existsSync(clipsIncoming) ? clipsIncoming : rootIncoming;

  return {
    incoming,
    publicDir: path.join("public", "templates", slug, "clips"),
    assetsModule: path.join("src", "app", `(${slug})`, slug, "videos.generated.ts"),
  };
}

export async function processClips(
  paths: ClipPaths,
  run?: Encoder,
): Promise<VideoAssets>;
export async function processClips(
  slug: string,
  paths: ClipPaths,
  run?: Encoder,
): Promise<VideoAssets>;
export async function processClips(
  first: string | ClipPaths,
  second?: ClipPaths | Encoder,
  third?: Encoder,
): Promise<VideoAssets> {
  const paths: ClipPaths = typeof first === "string" ? (second as ClipPaths) : first;
  const run: Encoder = typeof second === "function" ? second : (third ?? encode);

  mkdirSync(paths.publicDir, { recursive: true });
  const staging = mkdtempSync(path.join(paths.publicDir, ".encoding-"));
  const assets: VideoAssets = {};
  const outputs: string[] = [];

  try {
    const incomingMap = new Map<string, string>();
    if (existsSync(paths.incoming)) {
      for (const file of readdirSync(paths.incoming).sort()) {
        if (INPUT_VIDEO.test(file) && !file.endsWith("-m.mp4")) {
          const key = file.replace(INPUT_VIDEO, "");
          if (!incomingMap.has(key)) incomingMap.set(key, file);
        }
      }
    }

    const existingKeys = new Set<string>();
    if (existsSync(paths.publicDir)) {
      for (const file of readdirSync(paths.publicDir).sort()) {
        if (file.endsWith(".mp4") && !file.endsWith("-m.mp4")) {
          const key = file.replace(/\.mp4$/i, "");
          const desktop = path.join(paths.publicDir, `${key}.mp4`);
          const mobile = path.join(paths.publicDir, `${key}-m.mp4`);
          if (hasFile(desktop) && hasFile(mobile)) {
            existingKeys.add(key);
          }
        }
      }
    }

    const allKeys = Array.from(new Set([...incomingMap.keys(), ...existingKeys])).sort();

    for (const key of allKeys) {
      const incomingFile = incomingMap.get(key);
      const desktop = `${key}.mp4`;
      const mobile = `${key}-m.mp4`;

      if (incomingFile) {
        const input = path.resolve(paths.incoming, incomingFile);
        if (hasFile(input)) {
          for (const [file, isMobile] of [[desktop, false], [mobile, true]] as const) {
            const output = path.join(staging, file);
            await run(encodingArgs(input, output, isMobile));
            if (!hasFile(output)) throw new Error(`Encoder produced no file: ${file}`);
            outputs.push(file);
          }
          assets[key] = { desktop, mobile };
        }
      } else if (existingKeys.has(key)) {
        assets[key] = { desktop, mobile };
      }
    }

    // Publish only after every encode succeeds; a failed encode keeps existing media intact.
    for (const file of outputs) {
      renameSync(path.join(staging, file), path.join(paths.publicDir, file));
    }

    mkdirSync(path.dirname(paths.assetsModule), { recursive: true });
    writeFileSync(paths.assetsModule, renderVideoAssetsModule(assets));
    return assets;
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}

export const VALID_SLUGS = Array.from(
  new Set([
    "orrery",
    "keytu",
    "cairn",
    "koji",
    "wowflutter",
    "verane",
    "noctiluca",
    "iridia",
    "bathys",
    "aubade",
    "satsuma",
    "kinetic",
    "loophouse",
    "volume-zero",
    "openhouse",
    "handoff",
    "truecut",
    "nomi",
    "rill",
    "hiyas",
    ...Object.keys(TEMPLATES),
  ]),
);

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const slug = process.argv[2] as TemplateSlug | undefined;
  if (!slug || !VALID_SLUGS.includes(slug)) {
    console.error(`usage: npm run clips -- <${VALID_SLUGS.join("|")}>`);
    process.exit(1);
  }

  const paths = resolveClipPaths(slug);
  processClips(slug, paths).then(
    (assets) => {
      const count = Object.keys(assets).length;
      console.log(`clips: ${slug} → ${count} available`);
      if (count === 0) {
        if (slug === "truecut") {
          console.log("Awaiting assets/incoming/truecut/clips/hero-site-reel.mp4");
          console.log("Awaiting assets/incoming/truecut/clips/process-proof.mp4");
        } else {
          console.log(`Awaiting video clips in ${paths.incoming}/*.mp4`);
        }
      }
    },
    (error: unknown) => {
      console.error(error);
      process.exitCode = 1;
    },
  );
}
