#!/usr/bin/env bash
# Encodes KŌJI's food-flight clips for scroll scrubbing and records which ones exist.
#
#   bash scripts/encode-clips.sh [incoming-dir]
#
# In:  assets/incoming/koji/clips/dive-1..5.mp4, conn-1-2..conn-4-5.mp4 (from the Veo relay)
# Out: public/templates/koji/clips/<same names>.mp4  (H.264, crf 20, GOP 8 — scroll-world's desktop settings)
#      src/app/(koji)/koji/flight/clips.generated.ts  (which clips are present)
set -euo pipefail

in="${1:-assets/incoming/koji/clips}"
out="public/templates/koji/clips"
manifest="src/app/(koji)/koji/flight/clips.generated.ts"
mkdir -p "$out"

encode() { # src dst
  ffmpeg -v error -y -i "$1" -c:v libx264 -preset slow -crf 20 -pix_fmt yuv420p \
    -g 8 -keyint_min 8 -sc_threshold 0 -an -movflags +faststart "$2"
  echo "encoded $(basename "$2") ($(du -h "$2" | cut -f1))"
}

dives=()
for i in 1 2 3 4 5; do
  if [ -f "$in/dive-$i.mp4" ]; then encode "$in/dive-$i.mp4" "$out/dive-$i.mp4"; dives+=(true); else dives+=(false); fi
done
conns=()
for i in 1 2 3 4; do
  f="conn-$i-$((i + 1)).mp4"
  if [ -f "$in/$f" ]; then encode "$in/$f" "$out/$f"; conns+=(true); else conns+=(false); fi
done

join() { local IFS=", "; echo "$*"; }
cat > "$manifest" <<EOF
// Generated by scripts/encode-clips.sh — do not edit by hand.
export const CLIPS = {
  dives: [$(join "${dives[@]}")],
  connectors: [$(join "${conns[@]}")],
};
EOF
echo "manifest: $manifest"
