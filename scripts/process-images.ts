import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import sharp, { type Sharp } from "sharp";
import type { TemplateSlug } from "./templates.config";

const WIDTHS = [800, 1600] as const;
const INPUT = /\.(png|jpe?g|webp)$/i;

/** Cairn's tritone stops: black → dark blue → white. */
const STOPS: [number, [number, number, number]][] = [
  [0, [0x0b, 0x0c, 0x0e]],
  [0.5, [0x0f, 0x1e, 0x33]],
  [1, [0xf5, 0xf6, 0xf7]],
];

export function tritone(luma: number): [number, number, number] {
  const l = Math.min(1, Math.max(0, luma));
  const i = l <= 0.5 ? 0 : 1;
  const [l0, c0] = STOPS[i];
  const [l1, c1] = STOPS[i + 1];
  const t = (l - l0) / (l1 - l0);
  return [0, 1, 2].map((k) => Math.round(c0[k] + (c1[k] - c0[k]) * t)) as [number, number, number];
}

/** WOWFLUTTER's two-ink print: Rec.709 luma runs from tape black to uncoated stock, so no photo hue survives. */
export function inkOnStock(luma: number): [number, number, number] {
  const l = Math.min(1, Math.max(0, luma));
  const ink = [0x14, 0x11, 0x0f];
  const stock = [0xef, 0xe6, 0xd4];
  return [0, 1, 2].map((k) => Math.round(ink[k] + (stock[k] - ink[k]) * l)) as [number, number, number];
}

export type AssetRecord =Record<string, { w: number; h: number }>;

export function renderAssetsModule(assets: AssetRecord): string {
  const body = Object.keys(assets).length
    ? `{\n${Object.entries(assets)
        .map(([k, v]) => `  ${JSON.stringify(k)}: { "w": ${v.w}, "h": ${v.h} },`)
        .join("\n")}\n}`
    : "{}";
  return `// Generated by scripts/process-images.ts — do not edit by hand.\nexport const ASSETS: Record<string, { w: number; h: number }> = ${body};\n`;
}

export type ProcessPaths = { incoming: string; publicDir: string; assetsModule: string };

export async function processImages(slug: TemplateSlug, paths: ProcessPaths): Promise<AssetRecord> {
  const assets: AssetRecord = {};
  const inputs = existsSync(paths.incoming) ? readdirSync(paths.incoming).filter((f) => INPUT.test(f)).sort() : [];
  mkdirSync(paths.publicDir, { recursive: true });

  for (const file of inputs) {
    const key = file.replace(INPUT, "");
    let image: Sharp = sharp(path.join(paths.incoming, file)).rotate();
    if (slug === "keytu" || (slug as string) === "cairn") image = await applyLumaMap(image, tritone);
    else if (slug === "wowflutter") image = await applyLumaMap(image, inkOnStock);
    const meta = await image.clone().metadata();
    assets[key] = { w: meta.width ?? 0, h: meta.height ?? 0 };

    for (const width of WIDTHS) {
      const resized = image.clone().resize({ width, withoutEnlargement: true });
      await resized.clone().webp({ quality: 82 }).toFile(path.join(paths.publicDir, `${key}-${width}.webp`));
      await resized.clone().avif({ quality: 55 }).toFile(path.join(paths.publicDir, `${key}-${width}.avif`));
    }
  }

  mkdirSync(path.dirname(paths.assetsModule), { recursive: true });
  writeFileSync(paths.assetsModule, renderAssetsModule(assets));
  return assets;
}

/** Map every pixel's Rec.709 luma through a colour ramp, so no hue survives. */
async function applyLumaMap(image: Sharp, ramp: (luma: number) => [number, number, number]): Promise<Sharp> {
  const { data, info } = await image.removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const out = Buffer.alloc(info.width * info.height * 3);
  for (let p = 0, q = 0; p < data.length; p += info.channels, q += 3) {
    const luma = (0.2126 * data[p] + 0.7152 * data[p + 1] + 0.0722 * data[p + 2]) / 255;
    const [r, g, b] = ramp(luma);
    out[q] = r;
    out[q + 1] = g;
    out[q + 2] = b;
  }
  return sharp(out, { raw: { width: info.width, height: info.height, channels: 3 } });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const slug = process.argv[2] as TemplateSlug | undefined;
  if (!slug || !["orrery", "keytu", "cairn", "koji", "wowflutter", "verane", "sundial", "noctiluca", "iridia", "bathys", "aubade"].includes(slug)) {
    console.error("usage: npm run images -- <orrery|keytu|koji|wowflutter|verane|sundial|noctiluca|iridia|bathys|aubade>");
    process.exit(1);
  }
  processImages(slug, {
    incoming: `assets/incoming/${slug}`,
    publicDir: `public/templates/${slug}`,
    assetsModule: `src/app/(${slug})/${slug}/assets.generated.ts`,
  }).then(
    (assets) => console.log(`images: ${slug} → ${Object.keys(assets).length} processed`),
    (error: unknown) => {
      console.error(error);
      process.exit(1);
    },
  );
}
